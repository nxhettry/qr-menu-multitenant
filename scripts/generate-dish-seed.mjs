import ExcelJS from "exceljs";
import { writeFile } from "node:fs/promises";
import { normalizeDishName } from "../src/lib/dishes/normalize.ts";

const source = "docs/data/nepali-menu-items.xlsx";
const target = "supabase/migrations/202611010002_dish_catalog_seed.sql";
const qualifier = /\s*\((full|half)\)\s*$/i;

const workbook = new ExcelJS.Workbook();
await workbook.xlsx.readFile(source);
const dishes = new Map();
const skipped = [];
workbook.getWorksheet("Menu Items").eachRow((row, index) => {
  if (index === 1) return;
  const [, category, subcategory, name, nameNe, type, , tags, slug] = row.values.slice(1).map(value => (value ?? "").toString().trim());
  const displayName = name.replace(qualifier, "");
  const key = normalizeDishName(displayName);
  if (dishes.has(key)) { skipped.push(`${name} (same dish as ${dishes.get(key).name})`); return; }
  dishes.set(key, {
    slug, name: displayName, name_ne: nameNe || null, category: category || null,
    tags: [...new Set([type, subcategory, ...tags.split("|")].map(tag => tag.toLowerCase()).filter(Boolean))],
  });
});

const json = JSON.stringify([...dishes.values()]);
if (json.includes("$seed$")) throw new Error("Seed data contains the dollar-quote delimiter");
await writeFile(target, `-- Starter dish catalog generated by scripts/generate-dish-seed.mjs from ${source}. Re-running adds only dishes whose slug is new.
insert into public.dishes(slug, name, name_ne, category, tags)
select slug, name, name_ne, category, tags from jsonb_to_recordset($seed$${json}$seed$::jsonb)
  as seed(slug text, name text, name_ne text, category text, tags text[])
on conflict (slug) do nothing;
`);
console.log(`${dishes.size} dishes written to ${target}`);
for (const line of skipped) console.log(`  skipped: ${line}`);
