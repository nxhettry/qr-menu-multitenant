async function checkVatModeBrowser({ page, save }) {
  const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
  const settingsTab = page.getByRole("navigation", { name: "Restaurant workspace" }).getByRole("button", { name: "Settings & images", exact: true });
  const vatRate = page.getByLabel("VAT rate (%)", { exact: true });
  await vatRate.waitFor();
  assert(await fits(), "VAT settings must fit a phone viewport");
  await vatRate.fill("14");
  assert(await page.getByRole("radio", { name: /Excluding VAT/ }).isDisabled(), "mode change must wait for an unsaved VAT rate");
  await vatRate.fill("13");
  await page.getByRole("radio", { name: /Excluding VAT/ }).click();
  const dialog = page.getByRole("dialog", { name: "Switch to prices excluding VAT" });
  await dialog.waitFor();
  assert(await fits(), "VAT dialog must fit a phone viewport");
  await dialog.getByText("Phone momo").first().waitFor();
  assert((await dialog.locator("li").first().innerText()).includes("→"), "preview rows must show before and after prices");
  await mkdir("artifacts", { recursive: true });
  await page.waitForTimeout(500);
  await page.screenshot({ path: "artifacts/vat-dialog-mobile.png" });
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  assert(await page.getByRole("radio", { name: /Including VAT/ }).isChecked(), "cancelling must keep the saved mode");
  await page.getByRole("radio", { name: /Excluding VAT/ }).click();
  await dialog.getByRole("radio", { name: /Keep my numbers/ }).check();
  await dialog.getByText("will look different to guests").waitFor();
  await dialog.getByRole("radio", { name: /Keep what guests pay/ }).check();
  await save(dialog.getByRole("button", { name: "Apply change", exact: true }));
  await dialog.waitFor({ state: "detached" });
  assert(await page.getByRole("radio", { name: /Excluding VAT/ }).isChecked(), "saved mode must be reflected after conversion");
  await page.getByRole("navigation", { name: "Restaurant workspace" }).getByRole("button", { name: "Menu", exact: true }).click();
  const guestHint = page.getByText(/Guests pay Rs/).first();
  await guestHint.scrollIntoViewIfNeeded();
  await page.waitForTimeout(300);
  await page.screenshot({ path: "artifacts/vat-editor-exclusive-mobile.png" });
  await settingsTab.click();
  await page.getByRole("radio", { name: /Including VAT/ }).click();
  const back = page.getByRole("dialog", { name: "Switch to prices including VAT" });
  await back.getByRole("radio", { name: /Keep my numbers/ }).check();
  await save(back.getByRole("button", { name: "Apply change", exact: true }));
  await back.waitFor({ state: "detached" });
  assert(await page.getByRole("radio", { name: /Including VAT/ }).isChecked());
  console.log("PASS mobile VAT mode dialog previews both strategies, converts prices, shows guest prices in the editor and fits 390px");
}

export async function checkEditorBrowser({ base, cookie, restaurantId, draftId }) {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ?? (process.platform === "win32" ? "C:/Program Files/Google/Chrome/Application/chrome.exe" : undefined) });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const separator = cookie.indexOf("=");
    await context.addCookies([{ name: cookie.slice(0, separator), value: cookie.slice(separator + 1), url: base, sameSite: "Lax" }]);
    const page = await context.newPage();
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    const snapshotPath = `/api/dashboard/restaurants/${restaurantId}/menu`;
    async function save(button) {
      const refreshed = page.waitForResponse(response => response.url().includes(snapshotPath) && response.request().method() === "GET" && response.status() === 200);
      await button.click();
      try { return (await refreshed).json(); }
      catch (error) {
        await mkdir("artifacts", { recursive: true });
        await page.screenshot({ path: "artifacts/editor-save-failure.png", fullPage: true });
        throw new Error(`${error.message}\n${await page.locator("main").innerText()}`);
      }
    }
    await page.goto(`${base}/dashboard/${restaurantId}`);
    await page.getByRole("heading", { name: "Your menu", exact: true }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "editor must fit a phone viewport");
    await page.getByRole("button", { name: "+ Add category", exact: true }).click();
    await page.getByLabel("Category name", { exact: true }).fill("Browser specials");
    await page.getByLabel("Nepali name (optional)", { exact: true }).fill("विशेष परिकार");
    await save(page.getByRole("button", { name: "Save category", exact: true }));
    const category = page.locator("section").filter({ has: page.getByRole("heading", { name: "Browser specials", exact: true }) });
    await category.getByRole("button", { name: "+ Add item", exact: true }).click();
    await page.getByLabel("Item name", { exact: true }).fill("Phone momo");
    await page.getByLabel("Price (Rs)", { exact: true }).fill("220.05");
    await save(page.getByRole("button", { name: "Save item", exact: true }));
    const item = category.locator("li").filter({ has: page.getByRole("heading", { name: "Phone momo", exact: true }) });
    await save(item.getByRole("button", { name: "Available", exact: true }));
    await item.getByRole("button", { name: "Sold out", exact: true }).waitFor();
    await item.getByRole("button", { name: "More actions for Phone momo", exact: true }).click();
    await item.getByRole("button", { name: "Edit item", exact: true }).click();
    await page.getByRole("dialog", { name: "Edit item" }).waitFor();
    await page.getByLabel(/Use variants/).check();
    await page.getByRole("button", { name: "+ Add variant", exact: true }).click();
    await page.getByLabel("Variant name", { exact: true }).nth(0).fill("Veg");
    await page.getByLabel("Price (Rs)", { exact: true }).nth(0).fill("180.01");
    await page.getByRole("button", { name: "+ Add variant", exact: true }).click();
    await page.getByLabel("Variant name", { exact: true }).nth(1).fill("Buff");
    await page.getByLabel("Price (Rs)", { exact: true }).nth(1).fill("220.05");
    await page.getByLabel(/^Diet/).selectOption("NON_VEG");
    await page.getByLabel("Feature in specials banner", { exact: false }).check();
    await page.getByLabel("Available today", { exact: true }).last().check();
    await page.getByRole("button", { name: "Move variant 2 up", exact: true }).click();
    const variants = await save(page.getByRole("button", { name: "Save item", exact: true }));
    const savedItem = variants.categories.flatMap(category => category.items).find(item => item.name === "Phone momo");
    assert.deepEqual(savedItem.variants.map(variant => [variant.name, variant.price_minor]), [["Buff", 22005], ["Veg", 18001]]);
    assert.equal(savedItem.is_featured, true);
    await category.getByRole("button", { name: "Actions for Browser specials", exact: true }).click();
    const reordered = await save(category.getByRole("button", { name: "Move up", exact: true }));
    assert.equal(reordered.categories[0].name, "Browser specials");
    await item.getByRole("button", { name: "More actions for Phone momo", exact: true }).click();
    await item.getByRole("button", { name: "Add photo", exact: true }).click();
    const photo = page.getByRole("dialog", { name: "Item photo" });
    await photo.getByLabel("Upload item image", { exact: true }).setInputFiles({ name: "fake.png", mimeType: "image/png", buffer: Buffer.from("not a real image") });
    await photo.getByText("Choose a still JPEG, PNG, or WebP image smaller than 3 MB and 20 megapixels.", { exact: true }).waitFor();
    await photo.getByRole("button", { name: "Close", exact: true }).click();
    await category.getByRole("button", { name: "+ Add item", exact: true }).click();
    await page.getByLabel("Item name", { exact: true }).fill("Garden salad");
    await page.getByLabel("Price (Rs)", { exact: true }).fill("120");
    await page.getByLabel(/^Diet/).selectOption("VEG");
    await page.getByLabel("Feature in specials banner", { exact: false }).check();
    await save(page.getByRole("button", { name: "Save item", exact: true }));

    const guest = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await guest.route("https://res.cloudinary.com/**", route => route.fulfill({ contentType: "image/svg+xml", body: '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><rect width="800" height="600" fill="#a86534"/><circle cx="400" cy="300" r="210" fill="#f6e4c5"/><circle cx="400" cy="300" r="155" fill="#66804b"/></svg>' }));
    const publicPage = await guest.newPage();
    publicPage.on("pageerror", error => errors.push(error.message));
    await publicPage.goto(`${base}/renamed-kitchen`);
    await publicPage.getByRole("region", { name: "Restaurant specials" }).getByRole("heading", { name: "Phone momo", exact: true }).waitFor();
    await publicPage.getByRole("img", { name: "Live Kitchen logo", exact: true }).evaluate(image => image.decode());
    await publicPage.getByRole("region", { name: "Restaurant specials" }).locator("img").evaluate(image => image.decode());
    await publicPage.getByRole("button", { name: "Next special", exact: true }).click();
    await publicPage.getByRole("region", { name: "Restaurant specials" }).getByRole("heading", { name: "Garden salad", exact: true }).waitFor();
    await publicPage.getByRole("button", { name: "Previous special", exact: true }).click();
    assert.equal(await publicPage.locator('[data-diet="NON_VEG"]').count(), 1);
    assert.equal(await publicPage.locator('[data-diet="VEG"]').count(), 1);
    const colors = await publicPage.locator("[data-diet]").evaluateAll(nodes => nodes.map(node => ({ diet: node.dataset.diet, color: getComputedStyle(node).color })));
    assert(colors.find(item => item.diet === "VEG").color !== colors.find(item => item.diet === "NON_VEG").color);
    assert.equal(await publicPage.getByRole("button", { name: /cart|favo[u]?rite|add to/i }).count(), 0);
    const search = publicPage.getByRole("searchbox", { name: "Search items or categories" });
    await search.fill("Garden salad");
    await publicPage.getByRole("heading", { name: "Garden salad", exact: true }).waitFor();
    await publicPage.getByRole("heading", { name: "Phone momo", exact: true }).waitFor({ state: "hidden" });
    await search.fill("Browser specials");
    await publicPage.getByRole("heading", { name: "Phone momo", exact: true }).waitFor();
    await search.fill("no dish matches this");
    await publicPage.getByRole("heading", { name: "No matching dishes", exact: true }).waitFor();
    await publicPage.getByRole("button", { name: "Show all dishes", exact: true }).click();
    await publicPage.getByRole("navigation", { name: "Menu categories" }).getByRole("button", { name: "Lunch", exact: true }).click();
    await publicPage.getByRole("heading", { name: "Phone momo", exact: true }).waitFor({ state: "hidden" });
    await publicPage.getByRole("heading", { name: "Test thali", exact: true }).waitFor();
    await publicPage.getByRole("button", { name: "All dishes", exact: true }).click();
    await publicPage.getByRole("region", { name: "Restaurant specials" }).waitFor();
    await publicPage.getByRole("button", { name: "Specials", exact: true }).click();
    await publicPage.getByRole("heading", { name: "Test thali", exact: true }).waitFor({ state: "hidden" });
    await publicPage.getByRole("button", { name: "All dishes", exact: true }).click();
    assert(await publicPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "public menu must fit a phone viewport");
    const columns = await publicPage.locator("#menu-items section > div.grid").first().evaluate(node => getComputedStyle(node).gridTemplateColumns.split(" ").length);
    assert.equal(columns, 2);
    await mkdir("artifacts", { recursive: true });
    await publicPage.screenshot({ path: "artifacts/public-menu-mobile.png", fullPage: true });
    await publicPage.setViewportSize({ width: 320, height: 740 });
    assert(await publicPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "public menu must fit a narrow phone viewport");
    await publicPage.setViewportSize({ width: 1280, height: 900 });
    await publicPage.screenshot({ path: "artifacts/public-menu-desktop.png", fullPage: true });
    await guest.close();
    console.log("PASS public mobile search by dish/category, category filtering, two-column cards, specials saved from dashboard, diet colors and no cart/favourites");

    await page.getByRole("button", { name: "Settings & images", exact: true }).click();
    await page.getByLabel("Restaurant name", { exact: true }).fill("Browser Kitchen");
    await page.getByLabel("Menu address", { exact: false }).fill("browser-kitchen");
    await page.getByLabel("Theme color", { exact: false }).fill("#ffffff");
    await save(page.getByRole("button", { name: "Save settings", exact: true }));
    await page.getByRole("heading", { name: "Browser Kitchen", exact: true }).waitFor();
    await checkVatModeBrowser({ page, save });
    const old = await fetch(`${base}/renamed-kitchen`, { redirect: "manual" });
    assert.equal(old.status, 301);
    assert.equal(new URL(old.headers.get("location"), base).pathname, "/browser-kitchen");
    const previewOpened = context.waitForEvent("page");
    await page.getByRole("link", { name: "Phone preview ↗", exact: true }).click();
    const preview = await previewOpened;
    await preview.getByRole("heading", { name: "Phone momo", exact: true, level: 3 }).waitFor();
    await preview.close();
    await page.getByRole("button", { name: "Get QR code", exact: true }).click();
    await page.getByRole("heading", { name: "Your QR code", exact: true }).waitFor();
    const qrTab = page.getByRole("navigation", { name: "Restaurant workspace" }).getByRole("button", { name: "QR code", exact: true });
    assert.equal(await qrTab.getAttribute("aria-current"), "page");
    await qrTab.evaluate(node => new Promise(resolve => {
      const settled = () => getComputedStyle(node).backgroundColor === "rgb(255, 255, 255)" ? resolve() : requestAnimationFrame(settled);
      settled();
    }));
    const qrImage = page.getByRole("img", { name: /^QR code linking to / });
    await qrImage.waitFor();
    assert(await qrImage.evaluate(image => image.decode().then(() => true, () => false)), "QR preview must load");
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "QR tab must fit a phone viewport");
    await page.screenshot({ path: "artifacts/qr-tab-mobile.png", fullPage: true });
    for (const layout of ["cards", "poster"]) {
      const sheet = await context.newPage();
      await sheet.goto(`${base}/dashboard/${restaurantId}/print?layout=${layout}`);
      await sheet.getByRole("button", { name: "Print", exact: true }).waitFor();
      await sheet.screenshot({ path: `artifacts/qr-print-${layout}.png`, fullPage: true });
      await sheet.emulateMedia({ media: "print" });
      await sheet.screenshot({ path: `artifacts/qr-print-${layout}-print.png`, fullPage: true });
      await sheet.close();
    }
    const onboarding = await context.newPage();
    await onboarding.goto(`${base}/onboarding`);
    await onboarding.getByLabel("Restaurant name", { exact: true }).fill("Café Déjà Vu & Bar");
    assert.equal(await onboarding.getByRole("textbox", { name: "Your menu address" }).inputValue(), "cafe-deja-vu-and-bar");
    await onboarding.getByText(/cafe-deja-vu-and-bar is available$/).waitFor();
    await onboarding.getByRole("textbox", { name: "Your menu address" }).fill("browser-kitchen");
    await onboarding.getByText("That address is taken. Try adding your area, like browser-kitchen-thamel.", { exact: true }).waitFor();
    assert(await onboarding.getByRole("button", { name: "Create restaurant", exact: true }).isDisabled());
    await onboarding.screenshot({ path: "artifacts/onboarding-address-mobile.png", fullPage: true });
    await onboarding.close();
    await page.getByRole("button", { name: "Unpublish", exact: true }).click();
    await save(page.getByRole("button", { name: "Unpublish menu", exact: true }));
    assert((await (await fetch(`${base}/browser-kitchen`)).text()).includes("isn’t available right now"));
    await save(page.getByRole("button", { name: "Publish menu", exact: true }));
    assert((await (await fetch(`${base}/browser-kitchen`)).text()).includes("Phone momo"));
    await page.getByRole("button", { name: "Menu", exact: true }).click();
    await page.getByRole("heading", { name: "Phone momo", exact: true }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "saved menu must fit a phone viewport");
    await mkdir("artifacts", { recursive: true });
    await page.screenshot({ path: "artifacts/owner-editor-mobile.png", fullPage: true });
    await checkBulkMenuBrowser({ browser, page, base, restaurantId, save, errors });

    await page.goto(`${base}/dashboard/${draftId}`);
    await page.getByRole("heading", { name: "Secret Draft Name", exact: true }).waitFor();
    assert.equal(await page.getByRole("heading", { name: "Phone momo", exact: true }).count(), 0);
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await page.waitForURL("**/login");
    await page.goto(`${base}/dashboard/${restaurantId}`);
    await page.waitForURL("**/login");
    assert.equal(await page.getByRole("heading", { name: "Browser Kitchen", exact: true }).count(), 0);
    assert.deepEqual(errors, [], "browser must not report unhandled errors");
    console.log("PASS mobile browser category/item/variant forms, reordering, image validation, settings/rename, preview, QR tab and print sheets, address suggestions, publishing, tenant switch and logout");
  } finally { await browser.close(); }
}
